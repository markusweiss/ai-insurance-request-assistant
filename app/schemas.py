from enum import Enum

from pydantic import BaseModel, ConfigDict, Field


# Defines the urgency levels for customer requests.
class Urgency(str, Enum):
    LOW = "low"
    NORMAL = "normal"
    HIGH = "high"


# Defines the input structure for incoming customer requests.
class RequestAnalysisInput(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True)

    subject: str | None = Field(default=None, max_length=300)
    message: str = Field(min_length=10, max_length=12000)


# Stores information extracted from the customer request.
class ExtractedInformation(BaseModel):
    policy_number: str | None = None
    requested_start_date: str | None = None
    product_or_policy_type: str | None = None
    other_details: list[str] = Field(default_factory=list)


# Defines the structured analysis generated by the AI service.
class RequestAnalysis(BaseModel):
    category: str = Field(
        description="Business category, typically policy administration in the MVP."
    )
    customer_concern: str
    urgency: Urgency
    extracted_information: ExtractedInformation
    missing_information: list[str]
    summary: str
    recommended_next_step: str
    requires_human_review: bool = True
    limitations_note: str = (
        "No actual policy status has been verified. "
        "The analysis must be reviewed by an authorized person."
    )


# Defines the API response structure.
class RequestAnalysisOutput(BaseModel):
    analysis: RequestAnalysis
